"""Text-to-SQL agent over US housing market data.
Flow: question -> Claude writes SQL (structured output) -> DuckDB runs it read-only
-> on error, Claude gets one retry with the error message -> Claude explains the result.
"""

import os
import re
import time
from dataclasses import asdict, dataclass, field

import anthropic
import duckdb
from pydantic import BaseModel, Field

MODEL = os.environ.get("HOUSING_AGENT_MODEL", "claude-opus-5-5")
# USD per million tokens (input, output), used for the cost column in evals.
PRICES = {
    "claude-opus-5-5": (4.00, 20.00),
    "claude-sonnet-5-5": (2.00, 10.00),
    "claude-haiku-5-5": (0.10, 0.50),
}
MAX_ROWS = 200
MAX_ATTEMPTS = 2

SQL_SYSTEM = """You translate questions about the US housing market into a single DuckDB SQL query.

Database schema:
{schema}

Notes:
- Sales and starts are seasonally adjusted annual rates (SAAR) in thousands of units, one row per month per region.
  region is one of 'US', 'Northeast', 'Midwest', 'South', 'West'; 'US' is the national total, not a sum you need to compute.
- Monthly tables use the first day of the month as `month`. Mortgage rates are weekly.
- "Latest" means the most recent row in the table, not today's date.
- Write one read-only SELECT (CTEs allowed). Return only the columns needed to answer, with readable aliases.
- Express percentages as percent values (e.g. 12.5, not 0.125).
- If the data cannot answer the question (wrong geography, a metric that isn't in the schema, a single
  builder or city, a forecast), set can_answer to false and explain why in note."""

ANSWER_SYSTEM = """You are a housing market analyst. Answer the user's question in 2-4 sentences using only
the query result provided. Quote the key numbers with units (SAAR thousands, USD, %, months).
If the result is empty or looks wrong for the question, say so instead of guessing."""


class SQLQuery(BaseModel):
    can_answer: bool = Field(description="False if the schema cannot answer the question.")
    sql: str = Field(description="A single DuckDB SELECT query, or an empty string if can_answer is false.")
    note: str = Field(description="One sentence: the approach taken, or why the question can't be answered.")


@dataclass
class Result:
    question: str
    sql: str = ""
    columns: list = field(default_factory=list)
    rows: list = field(default_factory=list)
    answer: str = ""
    declined: bool = False
    error: str = ""
    attempts: int = 0
    latency_s: float = 0.0
    input_tokens: int = 0
    output_tokens: int = 0
    cost_usd: float = 0.0

    def to_dict(self) -> dict:
        d = asdict(self)
        d["rows"] = [[str(v) if not isinstance(v, (int, float)) else v for v in r] for r in self.rows]
        return d

#identify the available tables, cols, and data types -> to provide context about the dataset to claude.
def describe_schema(con: duckdb.DuckDBPyConnection) -> str:
    lines = []
    for (table,) in con.execute("SELECT table_name FROM information_schema.tables ORDER BY 1").fetchall():
        cols = con.execute(f"DESCRIBE {table}").fetchall()
        date_col = cols[0][0]
        lo, hi = con.execute(f"SELECT min({date_col}), max({date_col}) FROM {table}").fetchone()
        col_list = ", ".join(f"{c[0]} {c[1]}" for c in cols)
        lines.append(f"- {table}({col_list})  -- {lo} to {hi}")
    return "\n".join(lines)

#safeguard (basic guardrail) -> it checks if the sql statement generated by claude is safe
def check_read_only(sql: str) -> str:
    sql = sql.strip().rstrip(";").strip()
    if ";" in sql:
        raise ValueError("Only a single statement is allowed.")
    if not re.match(r"(?is)^\s*(select|with)\b", sql):
        raise ValueError("Only SELECT queries are allowed.")
    return sql


class HousingAgent:
    def __init__(self, db_path: str = "housing.duckdb", model: str = MODEL):
        self.con = duckdb.connect(db_path, read_only=True)
        self.model = model
        self._client = None
        self.sql_system = SQL_SYSTEM.format(schema=describe_schema(self.con))

    @property #used to create Anthropic api client
    def client(self) -> anthropic.Anthropic:
        # Created on first use, so the database and eval harness work without an API key.
        if self._client is None:
            self._client = anthropic.Anthropic()
        return self._client
    #execute the validated sql query
    def run_sql(self, sql: str) -> tuple[list, list]:
        cur = self.con.execute(check_read_only(sql))
        columns = [d[0] for d in cur.description]
        return columns, cur.fetchmany(MAX_ROWS)
    #track usage and cost of claude api
    def _track(self, result: Result, response) -> None:
        result.input_tokens += response.usage.input_tokens
        result.output_tokens += response.usage.output_tokens
        price_in, price_out = PRICES.get(self.model, (0.0, 0.0))
        result.cost_usd = (result.input_tokens * price_in + result.output_tokens * price_out) / 1e6
    #handles sql generation
    def write_sql(self, result: Result) -> None:
        messages = [{"role": "user", "content": result.question}]
        for attempt in range(1, MAX_ATTEMPTS + 1):
            result.attempts = attempt
            response = self.client.messages.parse(
                model=self.model,
                max_tokens=8000,
                system=self.sql_system,
                messages=messages,
                output_format=SQLQuery,
                output_config={"effort": "medium"},
            )
            self._track(result, response)
            if response.stop_reason == "refusal" or response.parsed_output is None:
                result.error = f"Model returned no query (stop_reason={response.stop_reason})."
                return

            query = response.parsed_output
            if not query.can_answer:
                result.declined = True
                result.answer = query.note
                return

            result.sql = query.sql
            try:
                result.columns, result.rows = self.run_sql(query.sql)
                result.error = ""
                return
            except Exception as e:  # DuckDB errors and our read-only check
                result.error = f"{type(e).__name__}: {e}"
                messages += [
                    {"role": "assistant", "content": query.model_dump_json()},
                    {"role": "user", "content": f"That query failed with: {result.error}\nReturn a corrected query."},
                ]
    #converts query result into natural language answer
    def explain(self, result: Result) -> None:
        table = "\n".join(
            [", ".join(result.columns)] + [", ".join(str(v) for v in row) for row in result.rows[:50]]
        )
        response = self.client.messages.create(
            model=self.model,
            max_tokens=4000,
            system=ANSWER_SYSTEM,
            messages=[{
                "role": "user",
                "content": f"Question: {result.question}\n\nSQL:\n{result.sql}\n\nResult ({len(result.rows)} rows):\n{table}",
            }],
            output_config={"effort": "low"},
        )
        self._track(result, response)
        result.answer = "".join(b.text for b in response.content if b.type == "text").strip()
    
    def ask(self, question: str, explain: bool = True) -> Result:
        start = time.perf_counter()
        result = Result(question=question)
        self.write_sql(result)
        if explain and not result.declined and not result.error:
            self.explain(result)
        result.latency_s = round(time.perf_counter() - start, 2)
        return result
